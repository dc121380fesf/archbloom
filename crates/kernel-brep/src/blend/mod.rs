//! 边过渡特征：倒角（chamfer）与圆角（fillet）。
//!
//! # 为什么归成一组
//!
//! 两者都在做同一件事的两种版本：
//!
//! ```text
//! 选边 → 两侧内缩 → 生成过渡面 → 在顶点处缝合角部
//! ```
//!
//! 差别只在**截面形状**：
//!
//! - 倒角：平面切角，截面是直线段
//! - 圆角：圆弧过渡，截面是圆弧
//!
//! 但角部那段——「顶点处若干条棱相交，要补一块面」——**是共通的**。
//! 现在两份各写一遍：`chamfer::corner_faces` 与 `fillet` 内联的球面片逻辑。
//! 归到同一组之后，「按选中棱数分类（0/1/2/3）」这件事才有可能只写一次。
//!
//! # 能力差异（如实记录）
//!
//! | | 倒角 | 圆角 |
//! |---|---|---|
//! | 盒子的全部 12 条棱 | ✓ | ✓ |
//! | 单条棱 | ✓ | ✓ |
//! | 圆柱顶/底圆（闭环棱） | ✓ | ✗ 需要「2 棱角部」，尚未实现 |
//!
//! 圆角在圆柱上报 `TopologyBroken` 而不是吐坏实体——见
//! [`crate::kernel`] 里 `fillet` 的自检。

pub mod chamfer;
pub mod fillet;

pub use chamfer::{chamfer_solid, ChamferOptions};
pub use fillet::{fillet_solid, FilletOptions};
